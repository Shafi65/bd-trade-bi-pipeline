"""Statistical tests behind the headline findings -> docs/STATS.md.

Division of labour: the Athena VIEWS define every metric (single source of truth);
this script only pulls their output and runs inference on it. If a metric definition
changes, it changes in SQL and these tests pick it up on the next run.

Tests (alpha = 0.05):
  1. Welch's t-test     — apparel vs non-apparel USD price trend (Q2).
     + Mann-Whitney U   — the same comparison on ranks (robust to the fat tails).
  2. Chi-squared test   — is a significantly-low destination price independent of
                          market group (traditional vs non-traditional)? (Q3)
  3. Spearman / Pearson — price trend vs volume trend: do price gains cost volume?

Run:  ./.venv/bin/python analysis/stats_tests.py
"""
import os
import sys

import numpy as np
from scipy import stats

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "scripts"))
from athena_run import run  # noqa: E402

ALPHA = 0.05
OUT = os.path.join(os.path.dirname(__file__), "..", "docs", "STATS.md")


def frame(sql):
    rows, _ = run(sql)
    header, body = rows[0], rows[1:]
    return {h: [r[i] for r in body] for i, h in enumerate(header)}


def verdict(p):
    return f"p = {p:.2g} -> {'significant' if p < ALPHA else 'not significant'} at alpha = {ALPHA}"


def main():
    md = ["# Statistical tests", "",
          "Generated by `analysis/stats_tests.py` from the Athena views. "
          "Alpha = 0.05 throughout. Population: clean products only "
          "(`NOT is_catch_all AND NOT is_volatile`, see `v_price_change`).", ""]

    # ---- 1. Welch t-test + Mann-Whitney: apparel vs non-apparel price trend ----
    d = frame("""SELECT segment, trend_cagr_usd FROM bd_trade.v_price_change
                 WHERE NOT is_catch_all AND NOT is_volatile""")
    seg = np.array(d["segment"])
    cagr = np.array(d["trend_cagr_usd"], dtype=float)
    a, n = cagr[seg == "Apparel"], cagr[seg == "Non-apparel"]
    t = stats.ttest_ind(a, n, equal_var=False)
    u = stats.mannwhitneyu(a, n, alternative="two-sided")
    md += ["## 1. Do apparel prices trend differently from non-apparel? (Welch t-test)", "",
           "| group | n | mean annual USD price trend | median |", "|---|---|---|---|",
           f"| Apparel | {len(a)} | {a.mean():+.2%} | {np.median(a):+.2%} |",
           f"| Non-apparel | {len(n)} | {n.mean():+.2%} | {np.median(n):+.2%} |", "",
           f"- **Welch's t-test:** t = {t.statistic:.2f}, {verdict(t.pvalue)}.",
           f"- **Mann-Whitney U (robustness, rank-based):** U = {u.statistic:.0f}, {verdict(u.pvalue)}.",
           f"- Variance check: apparel SD {a.std(ddof=1):.3f} vs non-apparel SD {n.std(ddof=1):.3f} "
           "— unequal, which is why Welch (no equal-variance assumption) is the right t-test.", ""]

    # ---- 2. Chi-squared: significantly-low price x market group ----
    d = frame("""SELECT market_group,
                        count_if(is_significant AND z_score < 0) AS low,
                        count(*) - count_if(is_significant AND z_score < 0) AS not_low
                 FROM bd_trade.v_destination_deviation GROUP BY market_group
                 ORDER BY market_group""")
    table = np.array([[int(x) for x in d["low"]], [int(x) for x in d["not_low"]]]).T
    chi2, p, dof, expected = stats.chi2_contingency(table)
    md += ["## 2. Are significantly-low prices concentrated in particular markets? (Chi-squared)", "",
           "Population: destinations of price-ERODED products (`v_destination_deviation`). "
           "'Low' = destination price |z| >= 2 below the product's norm.", "",
           "| market group | significantly low | not | % low | expected low if independent |",
           "|---|---|---|---|---|"]
    for g, row, exp in zip(d["market_group"], table, expected):
        md.append(f"| {g} | {row[0]} | {row[1]} | {row[0] / row.sum():.1%} | {exp[0]:.1f} |")
    md += ["", f"- **Chi-squared test of independence:** chi2 = {chi2:.1f}, dof = {dof}, {verdict(p)}.",
           f"- Smallest expected cell = {expected.min():.1f} (>= 5, so the chi-squared "
           "approximation is valid).", ""]

    # ---- 3. Correlation: price trend vs volume trend ----
    d = frame("""SELECT trend_cagr_usd, qty_cagr FROM bd_trade.v_price_change
                 WHERE NOT is_catch_all AND NOT is_volatile AND qty_cagr IS NOT NULL""")
    x = np.log1p(np.array(d["trend_cagr_usd"], dtype=float))   # back to log-slopes
    y = np.log1p(np.array(d["qty_cagr"], dtype=float))
    s = stats.spearmanr(x, y)
    r = stats.pearsonr(x, y)
    md += ["## 3. Do price gains come at the cost of volume? (correlation)", "",
           f"Population: {len(x)} clean products; both trends are log-linear slopes "
           "over their material years.", "",
           f"- **Spearman rho = {s.statistic:+.3f}**, {verdict(s.pvalue)} (rank-based, robust to outliers).",
           f"- Pearson r = {r.statistic:+.3f}, {verdict(r.pvalue)} (linear, for comparison).",
           "- Correlation is not causation: a negative rho is consistent with price-for-volume "
           "trade-offs (or with mix shifts within a code), not proof of either.", ""]

    with open(OUT, "w") as f:
        f.write("\n".join(md))
    print("\n".join(md))


if __name__ == "__main__":
    main()
